import fs from 'node:fs/promises';
const targets=await(await fetch('http://127.0.0.1:9228/json')).json();
const tab=targets.find(t=>t.type==='page'&&t.url.includes('CargoNest-Reports-Visual-Blueprint.html'));
if(!tab)throw Error('Document tab not found.');
const ws=new WebSocket(tab.webSocketDebuggerUrl);
await new Promise((resolve,reject)=>{ws.onopen=resolve;ws.onerror=reject;});
let id=0;const pending=new Map();ws.onmessage=e=>{const r=JSON.parse(e.data);if(r.id){const p=pending.get(r.id);pending.delete(r.id);r.error?p.reject(Error(r.error.message)):p.resolve(r.result);}};
const call=(method,params={})=>new Promise((resolve,reject)=>{const key=++id;pending.set(key,{resolve,reject});ws.send(JSON.stringify({id:key,method,params}));});
await call('Emulation.setEmulatedMedia',{media:'print'});
const result=await call('Runtime.evaluate',{expression:`Array.from(document.querySelectorAll('.page')).map((p,i)=>({page:i+1,clearance:Math.round(p.querySelector('footer').getBoundingClientRect().top-p.querySelector('.body').getBoundingClientRect().bottom),overflow:p.scrollWidth>p.clientWidth}))`,returnByValue:true});
console.log('Page layout:',JSON.stringify(result.result.value));
if(result.result.value.length!==7||result.result.value.some(p=>p.clearance<12||p.overflow)){await call('Browser.close');throw Error('Adjust layout before PDF delivery.');}
await call('Emulation.setDeviceMetricsOverride',{width:1160,height:820,deviceScaleFactor:1,mobile:false});
const screenshot=await call('Page.captureScreenshot',{format:'png',captureBeyondViewport:false});
await fs.writeFile(new URL('./CargoNest-Reports-Preview.png',import.meta.url),Buffer.from(screenshot.data,'base64'));
const pdf=await call('Page.printToPDF',{printBackground:true,preferCSSPageSize:true,displayHeaderFooter:false,marginTop:0,marginBottom:0,marginLeft:0,marginRight:0});
const bytes=Buffer.from(pdf.data,'base64');
const count=(bytes.toString('latin1').match(/\/Type\s*\/Page\b/g)||[]).length;
if(count!==7)throw Error('Unexpected PDF page count: '+count);
await fs.writeFile(new URL('./CargoNest-Reports-Visual-Blueprint.pdf',import.meta.url),bytes);
console.log('Verified PDF: '+count+' pages; '+bytes.length+' bytes.');
await call('Browser.close');ws.close();
